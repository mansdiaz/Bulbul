public class NoModificar {
    String hola;
    String queTal;

    //prueba

    public NoModificar(String hola, String queTal) {
        this.hola = hola;
        this.queTal = queTal;
    }

    public String getHola() {
        return hola;
    }

    public void setHola(String hola) {
        this.hola = hola;
    }

    public String getQueTal() {
        return queTal;
    }

    public void setQueTal(String queTal) {
        this.queTal = queTal;
    }




    
}
